import {
  mkdir,
  readFile,
  writeFile,
  copyFile,
  readdir,
  access,
  rm,
} from "node:fs/promises";
import { createHash } from "node:crypto";
import { parseCOR, SOURCE, SOURCE_SHA256, DICTIONARY_PATH } from "./ro-dictionary.mjs";
import sharp from "sharp";
await mkdir("public/dictionaries", { recursive: true });
await mkdir("public/ocr", { recursive: true });
await mkdir("public/licenses", { recursive: true });
for (const [source, name] of [
  ["react/LICENSE", "react"],
  ["react-dom/LICENSE", "react-dom"],
  ["tesseract.js/LICENSE.md", "tesseract-js"],
  ["tesseract.js-core/LICENSE", "tesseract-core"],
])
  await copyFile(`node_modules/${source}`, `public/licenses/${name}.txt`);
// Keep the unmodified official source for attribution and reproducible builds.
const sourcePath = "public/dictionaries/cor1.5.1.0.tsv";
let source;
try { source = await readFile(sourcePath); } catch {
  const response = await fetch(SOURCE, { signal: AbortSignal.timeout(120_000) });
  if (!response.ok) throw new Error(`COR download failed: ${response.status}`);
  source = Buffer.from(await response.arrayBuffer());
}
if (createHash("sha256").update(source).digest("hex") !== SOURCE_SHA256)
  throw new Error("The pinned COR source changed. Review the official release before updating the checksum.");
const words = parseCOR(source.toString("utf8"));
if (words.length < 100_000) throw new Error("COR dictionary is unexpectedly incomplete");
await writeFile(sourcePath, source);
const wordText = words.join("\n") + "\n";
const release = JSON.parse(await readFile("src/ro-release.json", "utf8"));
if (release.count !== words.length || release.sha256 !== createHash("sha256").update(wordText).digest("hex"))
  throw new Error("RO output differs from the reviewed release manifest");
await writeFile(`public/${DICTIONARY_PATH}`, wordText);
await writeFile("public/dictionaries/ro-metadata.json", JSON.stringify({
  edition: "Retskrivningsordbogen 5.1", corVersion: "1.5.1.0", source: SOURCE,
  sha256: SOURCE_SHA256, dictionarySha256: release.sha256, normering: "N", count: words.length,
  filter: "Exact forms, NFC uppercase, A-Z/AE/OE/AA, 2-15 letters. No inferred forms."
}, null, 2));
console.log(`Retskrivningsordbogen 5.1: ${words.length.toLocaleString()} approved forms`);
// Remove only retired assets generated by previous WordWin builds.
for (const name of ["en.txt", "da.txt", "en.version", "da.version", "en-license.txt", "da-license.txt", "en-source.md", "da-source.md", "da-source.aff", "da-source.dic"])
  await rm(`public/dictionaries/${name}`, { force: true });
await copyFile(
  "node_modules/tesseract.js/dist/worker.min.js",
  "public/ocr/worker.min.js",
);
for (const name of await readdir("node_modules/tesseract.js-core"))
  if (name.endsWith(".wasm.js") && name.includes("lstm"))
    await copyFile(
      `node_modules/tesseract.js-core/${name}`,
      `public/ocr/${name}`,
    );
await copyFile("node_modules/tesseract.js-core/LICENSE", "public/ocr/LICENSE");
for (const lang of ["eng", "dan"]) {
  const path = `public/ocr/${lang}.traineddata.gz`;
  try {
    await access(path);
  } catch {
    const url = `https://raw.githubusercontent.com/naptha/tessdata/806cd9adc8c6e8abc11c782db1818c990576bebc/4.0.0_fast/${lang}.traineddata.gz`;
    const response = await fetch(url);
    if (!response.ok)
      throw new Error(`Unable to download OCR data: ${response.status}`);
    await writeFile(path, Buffer.from(await response.arrayBuffer()));
  }
}
const icon = await readFile("public/icon.svg");
for (const [name, size] of [
  ["apple-touch-icon", 180],
  ["icon-192", 192],
  ["icon-512", 512],
])
  await sharp(icon).resize(size, size).png().toFile(`public/${name}.png`);
await writeFile(
  "public/asset-manifest.json",
  JSON.stringify([
    DICTIONARY_PATH,
    "dictionaries/ro-metadata.json",
    "ocr/worker.min.js",
    "ocr/eng.traineddata.gz",
    "ocr/dan.traineddata.gz",
    ...(await readdir("public/ocr"))
      .filter((n) => n.endsWith(".wasm.js"))
      .map((n) => `ocr/${n}`),
  ]),
);
